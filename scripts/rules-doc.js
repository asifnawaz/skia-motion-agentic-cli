#!/usr/bin/env node
// Writes docs/rules.md from the rule objects: lint rules (src/lint-rules.js), rig rules (src/rules.js RULES),
// the engine's own verdicts and the spec checks. Text above MARKER is hand-written and kept as it is.
// Run: npm run docs:rules. test/unit/rules-doc.test.js fails when docs/rules.md differs from render().
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LINT_RULES } from '../src/lint-rules.js';
import { RULES } from '../src/rules.js';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = join(ROOT, 'docs', 'rules.md');
export const MARKER = '<!-- generated by `npm run docs:rules` from the rule objects; edit the code, not below this line -->';

// Checks that are not in RULES or LINT_RULES (their ids are not exported). The test asserts each id is in its file.
export const FIXED = [
  { id: 'skac/samples', layer: 'engine', category: 'determinism', default: 'error', needs: '-', docs: 'motion/checks', file: 'src/rules.js',
    note: 'a channel or part holds NaN or a missing value, or the rig was never sampled; no rule runs then' },
  { id: 'skac/no-rules', layer: 'engine', category: 'request', default: 'error', needs: '-', docs: 'motion/checks', file: 'src/rules.js',
    note: 'every rule was skipped or off, so nothing was judged' },
  { id: 'skac/spec-beat', layer: 'spec (rig samples)', category: 'request', default: 'error', needs: 'spec.beats', docs: 'blind', file: 'src/spec.js',
    note: 'a beat in `<Name>.spec.json` is unmet: no move, wrong direction, or `reaches` not reached' },
  { id: 'skac/spec-point', layer: 'spec (pixels)', category: 'request', default: 'error', needs: 'spec.points', docs: 'blind', file: 'src/spec.js',
    note: 'the colour at a named point differs from the spec by more than 24 per channel' },
  { id: 'skac/rest-spec', layer: 'spec (pixels)', category: 'request', default: 'error', needs: 'spec.parts', docs: 'motion/checks', file: 'src/rest.js',
    note: "a part box's edges do not sit on the drawing's edges in the still at t=0" },
];

const cell = (s) => String(s).replace(/\|/g, '\\|');

/** First line of the comment directly above `const <var> = {` holding the rule, or the first `//` line inside it. */
const commentOf = (src, id) => {
  const at = src.indexOf(`id: '${id}'`);
  if (at < 0) return '';
  const start = src.lastIndexOf('\nconst ', at);
  const before = src.slice(0, start).split('\n');
  let k = before.length - 1;
  const above = [];
  while (k >= 0 && /^\s*(\/\/|\/\*\*|\*)/.test(before[k])) above.unshift(before[k--]);
  const clean = (l) => l.replace(/^\s*(\/\/|\/\*\*|\*\/?)\s?/, '').replace(/\*\/\s*$/, '').trim();
  const lines = above.map(clean).filter(Boolean);
  if (lines.length) return lines[0];
  const body = src.slice(at, src.indexOf('check(', at));
  const inner = /^\s*\/\/\s?(.*)$/m.exec(body);
  return inner ? inner[1].trim() : '';
};

const rigSources = () => ['src/rules.js', 'src/contact-rules.js'].map((f) => readFileSync(join(ROOT, f), 'utf8')).join('\n');

/** The generated part of docs/rules.md. */
export const table = () => {
  const src = rigSources();
  const rows = [
    '| id | layer | category | default | needs | doc topic | note |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const [id, r] of Object.entries(LINT_RULES)) {
    const def = r.default + (r.fixable ? ' (fixable)' : '');
    rows.push(`| \`${id}\` | lint | - | ${def} | source | \`${r.docs}\` | ${cell(r.fix || '-')} |`);
  }
  for (const r of Object.values(RULES)) {
    const needs = r.needs.length ? r.needs.map((k) => `\`${k}\``).join(', ') : '-';
    rows.push(`| \`${r.id}\` | ${r.layer} | ${r.category} | ${r.default} | ${needs} | \`${r.docs}\` | ${cell(commentOf(src, r.id) || '-')} |`);
  }
  for (const r of FIXED) rows.push(`| \`${r.id}\` | ${r.layer} | ${r.category} | ${r.default} | ${r.needs} | \`${r.docs}\` | ${cell(r.note)} |`);
  return `${rows.join('\n')}\n\n${Object.keys(LINT_RULES).length} lint rules, ${Object.keys(RULES).length} rig rules, ${FIXED.length} engine and spec checks.\n`;
};

/** docs/rules.md as it should be: the hand-written text above MARKER (all of `current` if it has none), then the table. */
export const render = (current) => {
  const i = current.indexOf(MARKER);
  const head = (i < 0 ? current : current.slice(0, i)).replace(/\s*$/, '\n\n');
  return `${head}${MARKER}\n\n${table()}`;
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const current = readFileSync(DOC, 'utf8');
  const next = render(current);
  if (next !== current) writeFileSync(DOC, next);
  console.log(`${DOC}: ${next === current ? 'unchanged' : 'written'}`);
}
