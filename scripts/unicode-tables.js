#!/usr/bin/env node
// Writes runtime/asset-unicode.ts: the code point ranges the worklet-safe text rules need, from this Node's Unicode data (\p classes).
// Worklets cannot rely on regular expressions with Unicode properties, so the runtime reads these tables instead.
// Run: npm run unicode:tables. test/unit/asset-ink.test.js fails when the file differs from render().
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'runtime', 'asset-unicode.ts');

function ranges(pattern) {
  const out = [];
  let start = -1;
  for (let code = 0; code <= 0x110000; code++) {
    const hit = code <= 0x10ffff && !(code >= 0xd800 && code <= 0xdfff) && pattern.test(String.fromCodePoint(code));
    if (hit && start < 0) start = code;
    if (!hit && start >= 0) {
      out.push(start, code - 1);
      start = -1;
    }
  }
  return out;
}

const lines = (numbers) => {
  const hex = numbers.map((n) => `0x${n.toString(16)}`);
  const rows = [];
  for (let i = 0; i < hex.length; i += 12) rows.push(`  ${hex.slice(i, i + 12).join(', ')},`);
  return rows.join('\n');
};

export function render() {
  const caseless = ranges(/^[\p{Lo}\p{Lm}]$/u);
  const lowercase = ranges(/^\p{Ll}$/u);
  const uppercase = ranges(/^\p{Lu}$/u);
  const digits = ranges(/^\p{Nd}$/u);
  const zeros = [];
  for (let i = 0; i < digits.length; i += 2) for (let zero = digits[i]; zero <= digits[i + 1]; zero += 10) zeros.push(zero);
  return `// Generated by \`npm run unicode:tables\` from Unicode ${process.versions.unicode}; do not edit.
// Ranges as flat [first, last, first, last, ...] pairs, ascending.

/** Letters with no case (\\p{Lo} and \\p{Lm}): Arabic, Hebrew, the Indic scripts, CJK and the rest. */
export const CASELESS_LETTERS: readonly number[] = [
${lines(caseless)}
];

/** Lowercase letters (\p{Ll}), from the Unicode data rather than the engine's case mapping, so Hermes and Node read a text alike. */
export const LOWERCASE_LETTERS: readonly number[] = [
${lines(lowercase)}
];

/** Capital letters (\p{Lu}). */
export const UPPERCASE_LETTERS: readonly number[] = [
${lines(uppercase)}
];

/** The zero of every decimal digit system (\\p{Nd}); each runs zero to zero + 9. */
export const DIGIT_ZEROS: readonly number[] = [
${lines(zeros)}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render();
  let current = '';
  try {
    current = readFileSync(FILE, 'utf8');
  } catch {}
  if (next !== current) writeFileSync(FILE, next);
  console.log(`${FILE}: ${next === current ? 'unchanged' : 'written'}`);
}
